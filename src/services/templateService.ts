import { AppSettings, Notice } from '../types/notice';

export type ResponseTemplateType = 'extension' | 'clarification' | 'dispute' | 'cure_compliance';

export interface ResponseTemplateOption {
  type: ResponseTemplateType;
  title: string;
  description: string;
  recommendedFor: string;
}

export const RESPONSE_TEMPLATES: ResponseTemplateOption[] = [
  {
    type: 'extension',
    title: 'Formal Request for 30-Day Extension of Time to Respond',
    description: 'Requests additional time to consult with CPA/legal counsel and compile accounting or compliance records.',
    recommendedFor: 'When deadlines are tight or CPA is reviewing records'
  },
  {
    type: 'clarification',
    title: 'Notice of Clarification & Transmittal of Requested Documents',
    description: 'Submits requested documents with an indexed transmittal sheet and requests formal receipt confirmation.',
    recommendedFor: 'Audits, identity verifications, or documentation requests'
  },
  {
    type: 'dispute',
    title: 'Formal Notice of Disagreement & Request for Informal Conference',
    description: 'Formally disputes alleged citation, fine, or deficiency and requests administrative conference/hearing.',
    recommendedFor: 'OSHA citations, disputed tax assessments, or improper penalties'
  },
  {
    type: 'cure_compliance',
    title: 'Certificate of Cure and Evidence of Full Compliance',
    description: 'Certifies that all alleged deficiencies or lease breaches have been fully abated with attached proof.',
    recommendedFor: 'Commercial lease cure notices and municipal code violations'
  }
];

export function generateDraftResponse(
  templateType: ResponseTemplateType,
  notice: Notice,
  settings: AppSettings
): string {
  const today = new Date().toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  const citationList = notice.legalCitations.map((c) => c.code).join(', ') || 'applicable statutory standards';
  const checklistList = notice.documentChecklist
    .map((d) => `  - [ ] Exhibit: ${d.name} (${d.description})`)
    .join('\n');

  if (templateType === 'extension') {
    return `DATE: ${today}

VIA CERTIFIED MAIL & ELECTRONIC SUBMISSION
To: ${notice.issuingAuthority}
Attention: Review Division / Compliance Officer
Reference / Case Number: ${notice.referenceNumber}
Taxpayer / Entity: ${settings.businessName} (EIN: ${settings.ein})
Original Notice Date: ${notice.issueDate}
Current Response Due Date: ${notice.deadlineDate || 'Stated Window'}

RE: FORMAL REQUEST FOR 30-DAY EXTENSION OF TIME TO RESPOND
    Regarding Notice: ${notice.title}

Dear Reviewing Officer,

Please be advised that the undersigned authorized representative of ${settings.businessName} is in receipt of the above-referenced notice dated ${notice.issueDate}.

We take all correspondence from ${notice.issuingAuthority} with utmost seriousness and diligence. The matter involves documentation and factual verification governed under ${citationList}.

In order to prepare an accurate, complete, and fully substantiated submission in accordance with all statutory requirements, our organization has retained professional advisory assistance (CPA / Legal Counsel) to review our historical books and records. 

Due to the scope of documentation required and the necessity of compiling verified exhibits, we respectfully request a thirty (30) day extension of the current response deadline, moving the deadline to [INSERT REQUESTED NEW DATE - SUGGESTED: 30 DAYS FROM CURRENT DEADLINE].

This request is made in good faith and not for the purpose of undue delay. We are actively compiling the following materials:
${checklistList}

Kindly confirm grant of this extension in writing to the email or physical address below.

Respectfully submitted,

___________________________________________
Authorized Representative: [NAME & TITLE]
${settings.businessName}
EIN: ${settings.ein}
Address of Record: [INSERT BUSINESS PHYSICAL ADDRESS]
Contact Email: ${settings.primaryEmail}
Direct Phone: [INSERT CONTACT PHONE NUMBER]

*** NOTICE: This draft was generated by Notice on the Desk for initial structuring. It requires factual verification and review by qualified legal or tax counsel prior to transmission. ***`;
  }

  if (templateType === 'clarification') {
    return `DATE: ${today}

VIA REGISTERED TRANSMISSION
To: ${notice.issuingAuthority}
Attention: Audit & Compliance Directorate
In Reference to: ${notice.referenceNumber}
Entity Name: ${settings.businessName} (EIN: ${settings.ein})
Notice Reference: ${notice.title} (Issued: ${notice.issueDate})

RE: TRANSMITTAL OF VERIFICATION DOCUMENTATION & STATEMENT OF CLARIFICATION

Dear Officer / Auditor,

On behalf of ${settings.businessName}, we are submitting this formal response and accompanying documentary evidence in direct reply to your inquiry dated ${notice.issueDate}.

1. BACKGROUND & STATEMENT OF FACTS:
Regarding the matter described in your correspondence (${notice.whyIssued.trigger}):
${settings.businessName} is an active commercial entity in good standing under the laws of ${settings.stateOfIncorporation}. We have conducted a comprehensive internal reconciliation of all relevant operational and financial records.

2. ENCLOSED DOCUMENTARY TRANSMITTALS:
In full satisfaction of the items requested in Notice ${notice.referenceNumber}, we have enclosed the following verified documentation:
${checklistList}

3. CLARIFYING DECLARATION:
All figures and statements provided herein have been cross-checked against our contemporaneous books of account. Should the department require additional electronic ledger files, point-of-sale exports, or sworn officer affidavits, please communicate directly with our appointed representative listed below.

We respectfully request written confirmation acknowledging receipt of this submission and the updated status of your case file.

Sincerely,

___________________________________________
Signatory: [OFFICER NAME], [TITLE]
${settings.businessName}
Email: ${settings.primaryEmail}
EIN: ${settings.ein}

*** NOTICE: This draft requires factual verification and review by qualified professional counsel prior to submission. ***`;
  }

  if (templateType === 'dispute') {
    return `DATE: ${today}

VIA CERTIFIED MAIL / RETURN RECEIPT REQUESTED
To: ${notice.issuingAuthority}
Attention: Regional Director / Hearing Appeals Unit
Notice / Citation Identifier: ${notice.referenceNumber}
Respondent Entity: ${settings.businessName} (EIN: ${settings.ein})
Date of Issuance: ${notice.issueDate}

RE: FORMAL NOTICE OF CONTEST, DISAGREEMENT & REQUEST FOR INFORMAL CONFERENCE
    Statutory Authority: ${citationList}

To Whom It May Concern:

PLEASE TAKE NOTICE that ${settings.businessName} ("Respondent"), through its authorized corporate officers, hereby formally contests and expresses disagreement with the findings, citations, and/or penalties set forth in Notice ${notice.referenceNumber} received on ${notice.receivedDate}.

1. TIMELINESS OF NOTICE:
This contest notice is timely filed within the statutory contest period specified under governing administrative rules (prior to ${notice.deadlineDate || 'the statutory expiration date'}).

2. SPECIFIC ITEMS CONTESTED:
Respondent specifically disputes the characterization of the alleged violations and the proposed civil penalties:
a) Proposed classification: The conditions identified during the inspection do not warrant the designated severity classification based on the actual operating controls in effect.
b) Immediate Good-Faith Remediation: Prior to and immediately upon receipt of this notice, Respondent instituted full corrective abatement measures, as detailed in the attached photographic and log exhibits.
c) Proposed Penalty Calculation: The penalty formula fails to credit Respondent's documented good-faith safety history and clean prior regulatory standing.

3. REQUEST FOR INFORMAL CONFERENCE:
Pursuant to governing administrative regulations, Respondent formally requests an Informal Conference with the Area Director / Presiding Officer to discuss:
  - Evidence of completed abatement;
  - Reclassification of the cited items;
  - Mitigation and reduction of proposed monetary assessments.

Please contact the undersigned promptly to confirm a mutually convenient conference date.

Respectfully submitted,

___________________________________________
Managing Representative: [NAME]
Title: Managing Director / Operations Officer
${settings.businessName}
Contact Email: ${settings.primaryEmail}

*** NOTICE: Formal legal contest documents carry jurisdictional filing deadlines. Have this draft reviewed immediately by licensed counsel. ***`;
  }

  // cure_compliance
  return `DATE: ${today}

VIA HAND DELIVERY & CERTIFIED TRANSMISSION
To: ${notice.issuingAuthority}
Reference: ${notice.referenceNumber}
Tenant / Obligor: ${settings.businessName}
Premises / Subject: [INSERT SUITE / PROPERTY IDENTIFIER]
Notice Date: ${notice.issueDate}
Stated Cure Deadline: ${notice.deadlineDate || '10 Days from Service'}

RE: CERTIFICATE OF CURE AND EVIDENCE OF COMPLIANCE
    In Response to Notice of Default dated ${notice.issueDate}

Dear Landlord / Designated Agent,

Please accept this letter as formal confirmation that ${settings.businessName} has fully cured, satisfied, and abated each and every alleged deficiency set forth in your Notice of Default dated ${notice.issueDate}.

1. PROOF OF CURE - NON-MONETARY ITEMS:
With respect to the requirement for Certificate of Insurance endorsement:
Enclosed herewith is an executed ACORD-25 Certificate of Insurance for Policy #[INSERT POLICY NUMBER], issued by [INSERT CARRIER], explicitly naming ${notice.issuingAuthority} as Additional Insured and Certificate Holder in strict compliance with the agreement terms.

2. MONETARY ITEMS / RECONCILIATION:
With respect to the monetary billing of [INSERT AMOUNT]:
[ ] Payment has been remitted via electronic funds transfer (Confirmation Ref #[INSERT WIRE REF]) under full reservation of rights to review annual itemized CAM expense audit logs.
[ ] Direct check has been tendered herewith.

3. DEMAND FOR CONFIRMATION OF GOOD STANDING:
Having fully satisfied and cured all alleged matters within the contractual cure period, we hereby request your prompt written acknowledgment confirming that the notice of default is formally withdrawn and that our agreement remains in full force and good standing.

Very truly yours,

___________________________________________
Authorized Signatory: [NAME]
Title: Managing Officer
${settings.businessName}
Email: ${settings.primaryEmail}

*** NOTICE: Contractual notices require strict compliance with delivery provisions in your lease or agreement. ***`;
}
